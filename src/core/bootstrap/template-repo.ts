/** Render the template-repo README with the version stamp filled in. Pure. */
export function renderTemplateReadme(version: string): string {
  const v = version.trim();
  if (!v) throw new Error('renderTemplateReadme: version must be non-empty');
  return `${TEMPLATE_README_LINES.join('\n').replaceAll('{{VERSION}}', v)}\n`;
}

export interface GenerateTemplateTreeOptions {
  /** Version stamp; defaults to the repo VERSION file (repo-only tooling). */
  version?: string;
  /** Repo root override (tests); default resolves from this module's location. */
  repoRoot?: string;
}

export interface GenerateTemplateTreeResult {
  outDir: string;
  version: string;
  /** Sorted repo-relative paths of every file written (determinism receipt). */
  files: string[];
}

function readRepoVersion(repoRoot?: string): string {
  const root = repoRoot ?? resolve(import.meta.dir, '..', '..', '..');
  const p = join(root, 'VERSION');
  if (!existsSync(p)) {
    throw new Error(
      `VERSION file not found at ${p} — pass opts.version explicitly (the generator is repo-only tooling)`,
    );
  }
  return readFileSync(p, 'utf8').trim();
}

/** Recursive, sorted (LC_ALL=C-equivalent byte order), '/'-joined relative
 * file listing. Exported for the determinism test's tree walk. */
export function listTreeFiles(dir: string, prefix = ''): string[] {
  const out: string[] = [];
  const entries = readdirSync(dir, { withFileTypes: true });
  for (const e of entries) {
    const rel = prefix ? `${prefix}/${e.name}` : e.name;
    if (e.isDirectory()) {
      if (e.name === '.git') continue; // never traverse a checkout's metadata
      out.push(...listTreeFiles(join(dir, e.name), rel));
    } else {
      out.push(rel);
    }
  }
  return out.sort();
}

/** Generate the full template-repo tree into `outDir`. */
export async function generateTemplateTree(
  outDir: string,
  opts: GenerateTemplateTreeOptions = {},
): Promise<GenerateTemplateTreeResult> {
  const version = (opts.version ?? readRepoVersion(opts.repoRoot)).trim();
  if (!version) throw new Error('generateTemplateTree: resolved version is empty');

  mkdirSync(outDir, { recursive: true });

  // 1. The shared render engine, minimal/deterministic mode: placeholder
  //    tokens retained, canonical provenance, no runtime state [CX2-14].
  await renderWorkspace(outDir, { minimal: true });

  // 2. Template manifest: initialized:false + frozen-epoch created_at.
  writeManifest(outDir, TEMPLATE_PLACEHOLDER_MANIFEST);

  // 3. Template README with the VERSION stamp.
  writeFileSync(join(outDir, 'README.md'), renderTemplateReadme(version), 'utf8');

  return { outDir, version, files: listTreeFiles(outDir) };
}

/**
 * Template-repo generator [D4, G7, A1, CX2-14].
 *
 * Builds the "Use this template" GitHub template-repo tree: the exact file set
 * `gbrain bootstrap render` produces, with every interview value still a
 * `{{TOKEN}}` placeholder. There is ONE rendering code path with two consumers
 * [D4]: this generator calls the same `renderWorkspace()` engine the desktop
 * bootstrap uses, in minimal/deterministic mode, then adds the two
 * template-only artifacts:
 *
 *  - `agent.json` from `TEMPLATE_PLACEHOLDER_MANIFEST` (`initialized: false` —
 *    the template/attach discriminator [CX2-1]).
 *  - A template `README.md` ("Use this template" instructions) stamped with
 *    the gbrain VERSION it was generated from; `bootstrap status` compares
 *    that stamp to the installed binary (adopter-skew check [CX-P1.11]).
 *
 * Byte-determinism [CX2-14]: two independent renders of the same commit are
 * byte-identical. No wall-clock timestamps anywhere — the only date in the
 * tree is the canonical epoch placeholder inside
 * `TEMPLATE_PLACEHOLDER_MANIFEST`. CI relies on this: the release workflow
 * publishes ONLY after a `diff -r` of fresh generator output against the
 * vendored tree at `templates/bootstrap/template-repo/` passes, and
 * `scripts/check-bootstrap-templates.sh` runs the same byte-diff OFFLINE [A1].
 *
 * Repo-only tooling: invoked via `scripts/generate-template-repo.ts` (CI +
 * guard script). Deliberately NOT wired into src/cli.ts and NOT bundled into
 * the compiled binary's command surface.
 */


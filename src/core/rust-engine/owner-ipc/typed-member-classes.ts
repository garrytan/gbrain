/**
 * Where the Rust store's typed members sit in the owner socket's confirming-read table (confirming-reads.ts). A member
 * the store serves is forwarded to the owner like any other, so each one is either a member that only reads or a write
 * with the read that tells whether it committed; test/rust-owner-ipc-confirming-reads.test.ts fails for a forwarded
 * member that is neither. A new typed member is added here, never left out: an unlisted one counts as a write with no
 * confirming read.
 *
 * A member is a read only when the code it runs changes nothing: its engine-sql function and the helpers it calls, and for a
 * member the Rust store serves, the store function (a `self.write` there is a write). Its name does not decide it: readJobInbox
 * marks messages read, selectFactsReconcileDrain settles due pages, and listOriginClaims takes advisory locks, so they are listed
 * below as writes. A lookup that only takes row locks (`SELECT ... FOR UPDATE`) writes nothing and stays a read.
 *
 * The reads are local-only: a remote caller sends the reads of routes.ts OWNER_IPC_REMOTE_READS and no others, so a
 * typed read reaches a remote caller only by being added there.
 */


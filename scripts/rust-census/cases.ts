/**
 * What the census runs: one or more invocations per CLI command, and the arguments of every MCP tool.
 *
 * Every invocation runs on its own copy of the seeded fixture brain (test/fixtures/rust-cli-parity-brain imported with
 * --no-embed, then `extract all --source db`), so a write never leaks into another case. Tokens in arguments:
 *   {fixture}  the fixture directory (read-only)
 *   {repo}     a git repository holding a copy of the fixture, fresh for this case
 *   {tmp}      an empty scratch directory for this case
 *   {uuid}     a fresh request id
 *
 * `skip` names why a command is not run: it never opens the brain's engine (host, network or interactive commands)
 * or it would start a long-lived process. Skipped commands are listed in the report, not hidden.
 */

export interface CliCase {
  /** Top-level command this case covers. */
  cmd: string;
  args: string[];
  /** Why the command is not run at all (no engine use, a daemon, interactive, host-wide side effects). */
  skip?: string;
  /** Text fed to stdin, when the command reads it. */
  stdin?: string;
  /** CLI steps run on each arm's copy before the case, untraced (the state the case writes over, such as a member). */
  before?: string[][];
}


const exitSpy = spyOn(process, 'exit').mockImplementation((code) => { throw new Error(`unexpected CLI exit: ${code}`); });
afterAll(() => exitSpy.mockRestore());
const home = mkdtempSync(join(tmpdir(), 'owner-quarantine-'));
let engine: PGLiteEngine;
const env = { GBRAIN_HOME: home, GBRAIN_AUDIT_DIR: home, GBRAIN_SELF_UPGRADE_MODE: 'off', OPENAI_API_KEY: undefined, ANTHROPIC_API_KEY: undefined };
beforeAll(async () => { engine = new PGLiteEngine(); await engine.connect({}); await engine.initSchema(); }, 120000);
afterAll(async () => { await withEnv(env, () => disposePersistenceConsumer(engine)); await engine.disconnect(); const trash = join(homedir(), '.Trash'); mkdirSync(trash, { recursive: true }); renameSync(home, join(trash, 'owner-quarantine-' + randomUUID())); });
const content = '---\ntitle: Archive Example\ntype: article\ntags: [relevance:noise]\n---\n\n' + 'Independent archive evidence for a retained original. '.repeat(30);
const snapshot = () => engine.readPageSnapshot('archive/example', { sourceId: 'default' });
test('exact revision hide preserves the original; ordinary writes cannot unhide it; clear restores it', () => withEnv(env, async () => {
  await importFromContent(engine, 'archive/example', content, { noEmbed: true });
  await importFromContent(engine, 'archive/keep', content.replace('Archive Example', 'Kept Example'), { noEmbed: true });
  await importFromContent(engine, 'atoms/example', content.replace('type: article', 'type: atom\nsource_slug: archive/example').replace('Archive Example', 'Derived Archive Atom'), { noEmbed: true });
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).toContain('atoms/example');
  const childFact = await engine.insertFact({ fact: 'Inherited archive assertion', kind: 'fact', entity_slug: 'atoms/example', visibility: 'world', source: 'test' }, { source_id: 'default' });
  await engine.executeRaw("UPDATE facts SET source_markdown_slug='atoms/example',row_num=1 WHERE id=$1", [childFact.id]);
  const factRows = async () => (await operations.find(o => o.name === 'recall')!.handler({ engine, config: { engine: 'pglite' }, remote: false, sourceId: 'default', dryRun: false, logger: { info() {}, warn() {}, error() {} } } as unknown as OperationContext, { entity: 'atoms/example', source_id: 'default' }) as { facts: unknown[] }).facts;
  expect((await factRows()).length).toBe(1);
  const proactiveSlugs = async (title = 'Archive Example') => (await operations.find(o => o.name === 'volunteer_context')!.handler({ engine, config: { engine: 'pglite' }, remote: false, sourceId: 'default', dryRun: false, logger: { info() {}, warn() {}, error() {} } } as unknown as OperationContext, { window: 'user: '+title+'\nuser: Find '+title, max_pages: 5 }) as { pages: Array<{ slug: string }> }).pages.map(p => p.slug);
  expect(await proactiveSlugs()).toContain('archive/example');
  expect(await proactiveSlugs('Derived Archive Atom')).toContain('atoms/example');

  await engine.addLink('archive/example', 'archive/keep', 'preserved mention', 'related_to', 'mentions');
  const edges = await engine.executeRaw('SELECT * FROM links ORDER BY id');
  expect(edges.length).toBeGreaterThan(0);
  const before = (await snapshot())!;
  await expect(runQuarantine(engine, ['hide', 'archive/example', '--source-id', 'default', '--expected-revision', 'stale', '--request-id', randomUUID()])).rejects.toMatchObject({ code: 'revision_conflict' });
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(false);
  const args = ['hide', 'archive/example', '--source-id', 'default', '--expected-revision', before.revision, '--request-id', randomUUID()];
  await runQuarantine(engine, args);
  const hidden = (await snapshot())!;
  expect(isQuarantined(hidden.page.frontmatter as Record<string, unknown>)).toBe(true);
  expect(hidden.page.compiled_truth).toBe(before.page.compiled_truth);
  expect(hidden.page.deleted_at).toBeNull();
  expect(hidden.tags).toEqual(before.tags);
  expect(await engine.executeRaw('SELECT * FROM links ORDER BY id')).toEqual(edges);
  expect(hidden.page.timeline).toBe(before.page.timeline);
  expect((await engine.readPageSnapshot('archive/keep', { sourceId: 'default' }))!.page.frontmatter).not.toHaveProperty('quarantine');
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).not.toContain('archive/example');
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).not.toContain('atoms/example');
  expect((await engine.readPageSnapshot('atoms/example', { sourceId: 'default' }))!.page.deleted_at).toBeNull();
  expect((await factRows()).length).toBe(0);
  expect(await proactiveSlugs()).not.toContain('archive/example');
  expect(await proactiveSlugs('Derived Archive Atom')).not.toContain('atoms/example');
  expect((await engine.executeRaw('SELECT id FROM facts WHERE id=$1', [childFact.id])).length).toBe(1);
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).toContain('archive/keep');
  expect((await discoverExtractablePages(engine, 'default')).map(x => x.slug)).not.toContain('archive/example');
  expect(await countExtractAtomsBacklog(engine, 'default')).toBe(1);
  await runQuarantine(engine, args);
  expect((await snapshot())!.revision).toBe(hidden.revision);
  await importFromContent(engine, 'archive/example', content, { noEmbed: true });
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(true);
  await importFromContent(engine, 'archive/example', content, { noEmbed: true, preserveGateMarkers: true });
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(true);
  await runQuarantine(engine, ['clear', 'archive/example', '--source-id', 'default', '--force', '--no-embed', '--json']);
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(false);
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).toContain('archive/example');
  expect((await engine.searchKeyword('Independent archive evidence')).map(x => x.slug)).toContain('atoms/example');
  expect(await countExtractAtomsBacklog(engine, 'default')).toBe(2);
  expect(await proactiveSlugs()).toContain('archive/example');
  expect(await proactiveSlugs('Derived Archive Atom')).toContain('atoms/example');
  expect((await factRows()).length).toBe(1);
}), 120000);


test('managed owner publishes the exclusion and restore without changing bodies or tags', () => withEnv(env, async () => {
  await engine.disconnect(); engine = new PGLiteEngine(); await engine.connect({}); await engine.initSchema();
  const root = join(home, 'content'); mkdirSync(root);
  await engine.executeRaw("UPDATE sources SET local_path=$1 WHERE id='default'", [root]);
  await claimWorktree(engine, 'default', root, localHostId());
  await activateSharedSkillPersistence(engine, { confirmQuiesced: true });
  const ctx = { engine, config: { engine: 'pglite' }, remote: false, dryRun: false, sourceId: 'default', deferEmbeds: true,
    writeWaitMs: 30000, logger: { info() {}, warn() {}, error() {} } } as unknown as OperationContext;
  await submitPageMutation(ctx, { operation: 'put_page', params: { slug: 'archive/example', source_id: 'default', content, request_id: randomUUID() } });
  await submitPageMutation(ctx, { operation: 'put_page', params: { slug: 'archive/keep', source_id: 'default', content: content.replace('Archive Example', 'Kept Example'), request_id: randomUUID() } });
  const before = (await snapshot())!;
  const hide = ['hide', 'archive/example', '--source-id', 'default', '--expected-revision', before.revision, '--request-id', randomUUID()];
  await withCoordinatedWrite(engine, ['default'], () => engine.addLink('archive/example', 'archive/keep', 'preserved mention', 'related_to', 'mentions'), TEST_WRITE_ATTRIBUTION);
  const links = await engine.executeRaw('SELECT * FROM links ORDER BY id');
  expect(links.length).toBeGreaterThan(0);
  await runQuarantine(engine, hide);
  const hidden = (await snapshot())!;
  expect(isQuarantined(hidden.page.frontmatter as Record<string, unknown>)).toBe(true);
  expect(hidden.page.compiled_truth).toBe(before.page.compiled_truth);
  expect(hidden.page.timeline).toBe(before.page.timeline);
  expect(hidden.tags).toEqual(before.tags);
  expect(await engine.executeRaw('SELECT * FROM links ORDER BY id')).toEqual(links);
  const read = await operations.find(o => o.name === 'get_page')!.handler({ ...ctx, remote: true,
    auth: { scopes: ['read'], sourceId: 'default' } } as unknown as OperationContext,
    { slug: 'archive/example', source_id: 'default', include_content: true }) as Record<string, unknown>;
  expect(read.compiled_truth ?? '').toBe('');
  expect(read.quarantined).toMatchObject({ body_omitted: true });
  await submitPageMutation(ctx, { operation: 'put_page', params: { slug: 'archive/example', source_id: 'default', content,
    expected_revision: hidden.revision, request_id: randomUUID() } });
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(true);
  await runQuarantine(engine, ['clear', 'archive/example', '--source-id', 'default', '--force', '--no-embed', '--json']);
  expect(isQuarantined((await snapshot())!.page.frontmatter as Record<string, unknown>)).toBe(false);
  expect((await snapshot())!.page.compiled_truth).toBe(before.page.compiled_truth);
}), 120000);

import json
import sys
from pathlib import Path
from playwright.sync_api import sync_playwright, expect

url = sys.argv[1]
output = Path(sys.argv[2])
output.mkdir(parents=True, exist_ok=True)
errors = []
with sync_playwright() as playwright:
    browser = playwright.chromium.launch(headless=True, channel="chrome")
    context = browser.new_context(viewport={"width": 1368, "height": 792}, color_scheme="dark")
    page = context.new_page()
    page.on("pageerror", lambda error: errors.append(str(error)))
    page.goto(url.split("#")[0])
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("heading", name="你好，开始探索你的知识")).to_be_visible()
    expect(page.get_by_role("button", name="收起菜单", exact=True)).to_be_visible()
    expect(page.get_by_role("navigation", name="PMBrain 主导航").get_by_text("知识库", exact=True)).to_be_visible()
    expect(page.locator("html")).to_have_attribute("data-theme", "light")
    expect(page.get_by_text("知识库 · 正常", exact=True)).to_be_visible()
    page.screenshot(path=str(output / "web-home.png"))
    page.get_by_role("navigation", name="PMBrain 主导航").get_by_role("button", name="知识助手", exact=True).click()
    expect(page.get_by_role("heading", name="把工作交给你的助手")).to_be_visible()
    expect(page.get_by_role("button", name="收起菜单", exact=True)).to_be_visible()
    page.screenshot(path=str(output / "web-assistant.png"))
    page.get_by_role("button", name="收起菜单", exact=True).click()
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("button", name="展开菜单", exact=True)).to_be_visible()
    page.get_by_role("button", name="展开菜单", exact=True).click()
    page.reload()
    page.wait_for_load_state("networkidle")
    expect(page.get_by_role("button", name="收起菜单", exact=True)).to_be_visible()
    context.close()
    personal = browser.new_context(viewport={"width": 1368, "height": 792}, color_scheme="light")
    personal_page = personal.new_page()
    personal_page.add_init_script("localStorage.setItem('pmbrain.admin.theme-mode', 'dark'); localStorage.setItem('pmbrain.navCollapsed', '1');")
    personal_page.goto(url.split("#")[0])
    personal_page.wait_for_load_state("networkidle")
    expect(personal_page.locator("html")).to_have_attribute("data-theme", "dark")
    expect(personal_page.get_by_role("button", name="展开菜单", exact=True)).to_be_visible()
    personal.close()
    narrow = browser.new_context(viewport={"width": 713, "height": 612})
    narrow_page = narrow.new_page()
    narrow_page.on("pageerror", lambda error: errors.append(str(error)))
    narrow_page.goto(url.split("#")[0])
    expect(narrow_page.get_by_role("navigation", name="PMBrain 主导航")).to_be_visible()
    expect(narrow_page.get_by_role("heading", name="你好，开始探索你的知识")).to_be_visible()
    narrow_page.set_viewport_size({"width": 1034, "height": 612})
    expect(narrow_page.get_by_role("navigation", name="PMBrain 主导航")).to_be_visible()
    narrow_page.set_viewport_size({"width": 713, "height": 612})
    narrow_page.reload()
    expect(narrow_page.get_by_role("navigation", name="PMBrain 主导航")).to_be_visible()
    narrow_page.get_by_role("navigation", name="PMBrain 主导航").get_by_role("button", name="知识助手", exact=True).click()
    expect(narrow_page.get_by_role("heading", name="把工作交给你的助手")).to_be_visible()
    assert narrow_page.locator(".wb-assistant-name").evaluate("node => node.getBoundingClientRect().height") < 30
    narrow_page.screenshot(path=str(output / "web-assistant-narrow.png"))
    narrow.close()
    mobile = browser.new_context(viewport={"width": 390, "height": 844}, is_mobile=True, has_touch=True)
    mobile_page = mobile.new_page()
    mobile_page.on("pageerror", lambda error: errors.append(str(error)))
    mobile_page.goto(url.split("#")[0])
    expect(mobile_page.locator("#root > .app")).to_be_visible()
    mobile_page.set_viewport_size({"width": 1034, "height": 844})
    expect(mobile_page.get_by_role("navigation", name="PMBrain 主导航")).to_be_visible()
    mobile_page.set_viewport_size({"width": 390, "height": 844})
    expect(mobile_page.locator("#root > .app")).to_be_visible()
    mobile.close()
    assert not errors, errors
    browser.close()
result = {"checks": ["same-home-entry", "expanded-navigation", "desktop-theme-under-dark-system", "real-ready-status", "assistant-with-full-navigation", "collapse-and-expand-reload", "existing-theme-and-navigation-preserved", "narrow-desktop-shared-shell", "resize-and-reload-shared-shell", "narrow-assistant", "mobile-shell-preserved-and-reactive"], "pageErrors": errors}
(output / "result.json").write_text(json.dumps(result, ensure_ascii=False, indent=2), encoding="utf-8")
print(json.dumps(result, ensure_ascii=False))

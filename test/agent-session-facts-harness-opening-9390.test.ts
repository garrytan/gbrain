/** #9390: Claude Code's slash-command records are not an opening the owner typed, so they must not make sessions a repeated_opening match. */
import { afterAll, beforeAll, beforeEach, describe, expect, test } from 'bun:test';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { PGLiteEngine } from '../src/core/pglite-engine.ts';
import { classifyAgentSessionFacts } from '../src/core/repair/agent-session-facts.ts';
import { resetPgliteState } from './helpers/reset-pglite.ts';

const CAVEAT = '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands. '
  + 'DO NOT respond to these messages or otherwise consider them in your response unless the user explicitly asks you to.</local-command-caveat>';
const COMMAND = '<command-name>/clear</command-name>\n<command-message>clear</command-message>\n<command-args></command-args>';
const BRIEF = 'You are worker agent seven for the release crew. Read the brief below, follow the repository rules, keep commits small, '
  + 'and report back to the coordinator with a summary of what changed and what is still open.';

describe('agent-session-facts opening key ignores harness slash-command records (#9390)', () => {
  let engine: PGLiteEngine;
  let base: string;

  beforeAll(async () => {
    engine = new PGLiteEngine();
    await engine.connect({});
    await engine.initSchema();
  });
  afterAll(async () => {
    await engine.disconnect();
    if (base) rmSync(base, { recursive: true, force: true });
  });
  beforeEach(async () => {
    await resetPgliteState(engine);
    if (base) rmSync(base, { recursive: true, force: true });
    base = mkdtempSync(join(tmpdir(), 'gbrain-asf-9390-'));
    mkdirSync(join(base, 'corpus'), { recursive: true });
  });

  async function classes(sessions: Record<string, string>) {
    const ids = new Map<string, number>();
    for (const [session, body] of Object.entries(sessions)) {
      writeFileSync(join(base, 'corpus', `${session}.txt`), body);
      const [row] = await engine.executeRaw<{ id: number }>(
        `INSERT INTO facts (source_id, entity_slug, fact, kind, visibility, source, source_session, attributed_to)
         VALUES ('default', 'people/alice-example', $1, 'preference', 'private', 'hook:writeback', $2, 'user') RETURNING id`, [`Fact of ${session}`, session]);
      ids.set(session, Number(row!.id));
    }
    const result = await classifyAgentSessionFacts(engine, ['default'], { corpusDir: join(base, 'corpus') });
    return Object.fromEntries([...ids].map(([s, id]) => [s, result.candidates.find(c => c.id === id)?.reason ?? 'none']));
  }

  test('interactive sessions opening with a slash command are not repeated_opening matches', async () => {
    const sessions: Record<string, string> = {};
    for (let n = 1; n <= 5; n++) {
      sessions[`own-${n}`] = `[user]\n${CAVEAT}\n\n[user]\n${COMMAND}\n\n[user]\nPlease help me plan item number ${n} of the launch checklist.\n\n[assistant]\nOn it.`;
    }
    const reasons = await classes(sessions);
    expect(Object.values(reasons)).toEqual(['none', 'none', 'none', 'none', 'none']);
  });

  test('real shared agent openings still match', async () => {
    const sessions: Record<string, string> = {};
    for (let n = 1; n <= 4; n++) sessions[`agent-${n}`] = `[user]\n${BRIEF}\nTask ${n}.\n\n[assistant]\nOn it.`;
    const reasons = await classes(sessions);
    expect(Object.values(reasons)).toEqual(Array(4).fill('repeated_opening'));
  });
});

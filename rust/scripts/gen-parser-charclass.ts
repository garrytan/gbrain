#!/usr/bin/env bun
/**
 * Regenerates rust/crates/gbrain-store/src/keyword/parser/charclass.rs: the Unicode character classes
 * the Rust port of PostgreSQL's default text search parser needs, measured on PGLite 0.5.16
 * (PostgreSQL 18.6, C.UTF-8 database) with `ts_parse` over every Unicode scalar value from U+0080 on.
 * Three tables come out:
 *
 *   ALPHA    a lone character is parsed as one word token (the parser's p_isalpha, iswalpha)
 *   SPECIAL  the character after an `a` is parsed into the same word token, and it is not ALPHA
 *            (the parser's p_isspecial: zero width and spacing marks)
 *   SPACE    the character after `..` is parsed as blank (iswspace)
 *
 *   bun rust/scripts/gen-parser-charclass.ts           # check: exit 1 if the committed file differs
 *   bun rust/scripts/gen-parser-charclass.ts --write   # rewrite the file
 *
 * Needs the network once, to install PGLite 0.5.16 (see lib/pglite-golden.ts); takes about 10 seconds.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { installPglite, PGLITE_VERSION } from './lib/pglite-golden.ts';

const target = resolve(dirname(fileURLToPath(import.meta.url)), '../crates/gbrain-store/src/keyword/parser/charclass.rs');
const write = process.argv.includes('--write');

const { PGlite } = await import(await installPglite());
const db = new PGlite();
const version = (await db.query('select version() as v')).rows[0].v as string;
if (!version.startsWith('PostgreSQL 18.6 ')) throw new Error(`need PostgreSQL 18.6, got ${version}`);
console.log(`PGLite ${PGLITE_VERSION}: ${version}`);

const WORD_TOKEN = 2; // tokid of `word` in the default parser
const BLANK_TOKEN = 19; // tokid of `blank`
const scalars = `generate_series(128, 1114111) cp where cp not between 55296 and 57343`;
const measure = async (condition: string): Promise<number[]> =>
  (await db.query(`select cp from ${scalars} and ${condition} order by cp`)).rows.map((r: { cp: number }) => r.cp);

const alpha = await measure(`(select count(*) = 1 and min(tokid) = ${WORD_TOKEN} from ts_parse('default', chr(cp)))`);
const alphaSet = new Set(alpha);
const special = (await measure(`(select count(*) = 1 and min(tokid) = ${WORD_TOKEN} from ts_parse('default', 'a' || chr(cp)))`)).filter((cp) => !alphaSet.has(cp));
const space = await measure(`(select tokid = ${BLANK_TOKEN} and token = '..' from ts_parse('default', '..' || chr(cp)) limit 1)`);

function table(name: string, doc: string, scalarValues: number[]): string {
  const ranges: [number, number][] = [];
  for (const cp of scalarValues) {
    const last = ranges[ranges.length - 1];
    if (last && last[1] + 1 === cp) last[1] = cp;
    else ranges.push([cp, cp]);
  }
  const hex = (n: number) => '0x' + n.toString(16).toUpperCase();
  const rows = ranges.map(([a, b]) => `    (${hex(a)}, ${hex(b)}),\n`).join('');
  return `/// ${doc}\npub(super) const ${name}: &[(u32, u32)] = &[\n${rows}];\n`;
}

const generated =
  [
    '//! Character classes of the PGLite C.UTF-8 database, measured with `ts_parse` over every Unicode scalar',
    '//! value (see `parser.rs`). Non-ASCII only; ranges are inclusive and sorted.',
    '//! Generated by `bun rust/scripts/gen-parser-charclass.ts --write`; do not edit by hand.',
    '//! Derived from PostgreSQL 18.6; licence and notice: third-party/postgresql/NOTICE.md',
    '',
  ].join('\n') +
  '\n' +
  [
    table('ALPHA', 'iswalpha, code points >= 0x80.', alpha),
    table('SPECIAL', 'p_isspecial and not iswalpha (zero-width and spacing marks), code points >= 0x80.', special),
    table('SPACE', 'iswspace, code points >= 0x80.', space),
  ].join('\n');

if (write) {
  writeFileSync(target, generated);
  console.log(`wrote ${target}`);
} else if (readFileSync(target, 'utf8') === generated) {
  console.log('gen-parser-charclass: charclass.rs same');
} else {
  console.error('gen-parser-charclass: charclass.rs differs from the PostgreSQL 18.6 measurement; run with --write and review the diff');
  process.exit(1);
}

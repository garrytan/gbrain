/// The offset of a fixed-offset abbreviation, in seconds east of UTC.
pub(super) fn fixed_abbreviation(word: &str) -> Option<i64> {
    FIXED_ZONE_ABBREVIATIONS
        .binary_search_by(|(name, _)| (*name).cmp(word))
        .ok()
        .map(|i| FIXED_ZONE_ABBREVIATIONS[i].1)
}
